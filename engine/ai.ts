import type { AIPrompt, AIResponse, RecoveryAction } from './types.js';
import type { NetworkWorld } from './graph.js';
import { generateCandidates, validateAction } from './recovery.js';

export interface AIAdapter {
  enabled(): boolean;
  modelId(): string;
  complete(prompt: AIPrompt, world: NetworkWorld): Promise<AIResult>;
}

export interface AIResult {
  mode: 'real' | 'fallback';
  model: string;
  parsed?: AIResponse;
  raw?: string;
  latencyMs?: number;
  promptTokens?: number;
  completionTokens?: number;
  attempts?: number;
  error?: string;
  rejectedNotes?: string[];
}

export interface NebiusConfig {
  apiKey?: string;
  baseUrl?: string;
  model?: string;
  fetchImpl?: typeof fetch;
}

export const DEFAULT_MODEL = 'nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B';
export const DEFAULT_BASE_URL = 'https://api.tokenfactory.nebius.com/v1';

const TIMEOUT_MS = 25_000;
const MAX_ATTEMPTS = 3;

const SYSTEM_PROMPT = `You are the recovery planner of AETHER-NIM, a network digital twin for infrastructure operations.

You receive a structured incident report with REAL measured network state (algebraic connectivity λ2 of the weighted Laplacian, connected components, served demand pairs, bottlenecks) and a list of FEASIBLE candidate actions generated by deterministic graph analysis.

Your job:
1) Diagnose the most likely root cause from the measurements.
2) Rank the provided candidate actions, best-first (do NOT invent new actions, node ids, edge ids or measurements).
3) Explain briefly what you expect to happen and what the deterministic verifier must confirm.

Additional rules:
- Output ONLY a single JSON object, no markdown, no prose outside JSON, no code fences.
- JSON schema:
{
  "incident_summary": string,
  "root_cause_hypotheses": string[],
  "proposed_actions": [{"action": {"type": "RestoreEdge"|"RestoreNode"|"OpenCandidate"|"Retune", ...}, "rationale": string, "confidence": number}],
  "reasoning_summary": string,
  "expected_outcome": string,
  "risks": string[],
  "confidence": number,
  "verification_requirements": string[]
}
- Allowed action payloads (from the feasible list only):
  {"type":"RestoreEdge","edgeId":id} | {"type":"RestoreNode","nodeId":id} | {"type":"OpenCandidate","edgeId":id} | {"type":"Retune","edgeId":id,"toLatencyMs":number}
- confidence is between 0 and 1.
- The deterministic optimizer independently evaluates every action against the measured graph; incorrect proposals will be rejected.`;

export class NebiusAdapter implements AIAdapter {
  private key: string | undefined;
  private base: string;
  private model: string;
  private doFetch: typeof fetch;

  constructor(cfg: NebiusConfig = {}) {
    this.key = cfg.apiKey;
    this.base = (cfg.baseUrl || DEFAULT_BASE_URL).replace(/\/$/, '');
    this.model = cfg.model || DEFAULT_MODEL;
    // workerd requires fetch bound to the global scope ('Illegal invocation' otherwise)
    this.doFetch = cfg.fetchImpl || fetch.bind(globalThis);
  }

  enabled(): boolean { return !!this.key; }
  modelId(): string { return this.model; }

  async complete(prompt: AIPrompt, world: NetworkWorld): Promise<AIResult> {
    if (!this.key) {
      return { mode: 'fallback', model: this.model, error: 'NEBIUS_API_KEY not configured — running in deterministic fallback mode' };
    }
    const userContent = JSON.stringify({ incident_report: prompt }, null, 1);
    let lastError = 'unknown error';
    let raw = '';
    for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
      const t0 = Date.now();
      try {
        const res = await this.doFetch(`${this.base}/chat/completions`, {
          method: 'POST',
          signal: AbortSignal.timeout(TIMEOUT_MS),
          headers: {
            Authorization: `Bearer ${this.key}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            model: this.model,
            temperature: 0.6,
            top_p: 0.95,
            max_tokens: 2500,
            // Nemotron 3 reasoning mode is controlled by the chat template;
            // deterministic structured output is wanted → disable thinking.
            chat_template_kwargs: { enable_thinking: false },
            messages: [
              { role: 'system', content: SYSTEM_PROMPT },
              { role: 'user', content: attempt === 1 ? userContent : `${userContent}\n\nREMINDER: reply with ONLY the JSON object.` },
            ],
          }),
        });
        const latencyMs = Date.now() - t0;
        if (!res.ok) {
          lastError = `HTTP ${res.status} from Token Factory`;
          if (res.status === 401 || res.status === 403) break; // auth → stop retrying
          if (res.status === 429) { await sleep(1200); continue; }
          continue;
        }
        const data = (await res.json()) as {
          choices?: { message?: { content?: string; reasoning_content?: string } }[];
          usage?: { prompt_tokens?: number; completion_tokens?: number };
          model?: string;
        };
        const choice = data.choices?.[0]?.message;
        const content = choice?.content ?? '';
        const reasoning = (choice as { reasoning?: string } | undefined)?.reasoning ?? '';
        raw = content;
        const candidates = extractJsonObjects(content);
        if (candidates.length === 0 && reasoning) candidates.push(...extractJsonObjects(reasoning));
        for (const candidate of candidates) {
          const parsed = validateAIResponse(candidate, world);
          if (typeof parsed === 'string') { lastError = `schema/feasibility: ${parsed}`; continue; }
          return {
            mode: 'real',
            model: data.model || this.model,
            parsed,
            latencyMs,
            promptTokens: data.usage?.prompt_tokens,
            completionTokens: data.usage?.completion_tokens,
            attempts: attempt,
          };
        }
      } catch (err) {
        lastError = err instanceof Error ? err.message : String(err);
      }
    }
    return { mode: 'fallback', model: this.model, raw: raw.slice(0, 500), attempts: MAX_ATTEMPTS, error: lastError };
  }
}

/** Extract candidate JSON objects by balanced-brace scan. */
export function extractJsonObjects(text: string): unknown[] {
  const out: unknown[] = [];
  const cleaned = text.replace(/<think>[\s\S]*?<\/think>/g, '');
  let start = cleaned.indexOf('{');
  while (start >= 0) {
    let depth = 0, inStr = false, esc = false, end = -1;
    for (let i = start; i < cleaned.length; i++) {
      const ch = cleaned[i];
      if (inStr) { if (esc) esc = false; else if (ch === '\\') esc = true; else if (ch === '"') inStr = false; continue; }
      if (ch === '"') inStr = true;
      else if (ch === '{') depth++;
      else if (ch === '}') { depth--; if (depth === 0) { end = i; break; } }
    }
    if (end > start) {
      try { out.push(JSON.parse(cleaned.slice(start, end + 1))); } catch { /* skip malformed */ }
      start = cleaned.indexOf('{', end + 1);
    } else break;
  }
  return out;
}

/** Structural + feasibility validation; returns AIResponse or a rejection reason string. */
export function validateAIResponse(v: unknown, world: NetworkWorld): AIResponse | string {
  if (typeof v !== 'object' || v === null) return 'not an object';
  const o = v as Record<string, unknown>;
  const strArr = (x: unknown): boolean => Array.isArray(x) && x.every((i) => typeof i === 'string');
  if (typeof o.incident_summary !== 'string') return 'missing incident_summary';
  if (!strArr(o.root_cause_hypotheses)) return 'root_cause_hypotheses must be string[]';
  if (!Array.isArray(o.proposed_actions)) return 'proposed_actions must be an array';
  if (typeof o.reasoning_summary !== 'string') return 'missing reasoning_summary';
  if (typeof o.expected_outcome !== 'string') return 'missing expected_outcome';
  if (!strArr(o.risks)) return 'risks must be string[]';
  if (typeof o.confidence !== 'number' || o.confidence < 0 || o.confidence > 1) return 'confidence must be in [0,1]';
  if (!strArr(o.verification_requirements)) return 'verification_requirements must be string[]';

  const proposed: AIResponse['proposed_actions'] = [];
  const knownActions = new Set(generateCandidates(world).map((c) => sortActionKey(c.action)));
  let feasible = 0;
  for (const pa of o.proposed_actions) {
    if (typeof pa !== 'object' || pa === null) return 'proposed_actions entry must be an object';
    const p = pa as Record<string, unknown>;
    const action = p.action as RecoveryAction | undefined;
    if (!action || typeof action !== 'object') return 'missing action payload';
    const conf = p.confidence;
    if (typeof conf !== 'number' || conf < 0 || conf > 1) return 'proposed action confidence must be in [0,1]';
    const v2 = validateAction(world, action);
    if (!v2.ok) return `proposal {${sortActionKey(action)}} infeasible: ${v2.reason}`;
    feasible++;
    proposed.push({ action, rationale: typeof p.rationale === 'string' ? p.rationale : '', confidence: conf });
    if (!knownActions.has(sortActionKey(action))) return `proposal ${sortActionKey(action)} not in the measured feasible candidate list`;
  }
  void feasible;
  return {
    incident_summary: o.incident_summary,
    root_cause_hypotheses: o.root_cause_hypotheses as string[],
    proposed_actions: proposed,
    reasoning_summary: o.reasoning_summary,
    expected_outcome: o.expected_outcome,
    risks: o.risks as string[],
    confidence: o.confidence,
    verification_requirements: o.verification_requirements as string[],
  };
}

function sortActionKey(a: RecoveryAction): string {
  switch (a.type) {
    case 'RestoreEdge': return `RestoreEdge:${a.edgeId}`;
    case 'OpenCandidate': return `OpenCandidate:${a.edgeId}`;
    case 'Retune': return `Retune:${a.edgeId}@${a.toLatencyMs}`;
    case 'RestoreNode': return `RestoreNode:${a.nodeId}`;
    default: return String((a as { type?: string }).type);
  }
}

function sleep(ms: number): Promise<void> { return new Promise((r) => setTimeout(r, ms)); }
